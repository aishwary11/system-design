#!/usr/bin/env node
/**
 * hoist-runtime.mjs — move the Archify viewer runtime out of every generated
 * diagram page into one shared pair of files.
 *
 * Why: `archify deliver` writes each page self-contained, so the identical
 * ~186 KB stylesheet and ~451 KB engine (plus the ~26 KB i18n payload) were
 * copied into all 89 pages — ~42 MB of duplicate bytes and 89 copies to edit.
 *
 * What moves:
 *   <style>…</style>                                -> diagrams/archify.css
 *   <script>…engine…</script>                       -> diagrams/archify.js
 *   <script id="archify-guided-views-data">…</script>  -> folded into archify.js
 *   <script id="archify-i18n-data">…</script>          -> folded into archify.js
 *
 * The two JSON blocks are read by the engine with getElementById + JSON.parse,
 * so archify.js recreates those elements from embedded data before the engine
 * runs. Behaviour is unchanged; only the bytes move.
 *
 * The small pre-paint theme bootstrap in <head> stays inline on purpose: it
 * must run before first paint to avoid a light/dark flash.
 *
 * Idempotent: pages that already reference the shared files are left alone.
 *
 * Usage:
 *   node tools/hoist-runtime.mjs                 # hoist (default)
 *   node tools/hoist-runtime.mjs --self-contained # re-inline into every page
 *   node tools/hoist-runtime.mjs --check         # report only, exit 1 if unhoisted
 *
 * Also called by tools/archify-all.mjs after `deliver`, so regenerated pages
 * are hoisted again automatically.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIAGRAMS = join(ROOT, 'diagrams');
const CSS_OUT = join(DIAGRAMS, 'archify.css');
const JS_OUT = join(DIAGRAMS, 'archify.js');

const PAGE_DIRS = ['', 'concepts', 'features', 'system-design']
  .map(d => (d ? join(DIAGRAMS, d) : DIAGRAMS))
  .filter(existsSync);

// Block bodies must not span a closing tag: a bare `[\s\S]{N,}` would run from
// the first <script> across the page's SVG and into a later block, which makes
// every page look like it has a unique engine.
const STYLE_RE = /<style[^>]*>((?:(?!<\/style>)[\s\S]){50000,})<\/style>/;
const ENGINE_RE = /<script>((?:(?!<\/script>)[\s\S]){200000,})<\/script>/;
const I18N_RE = /<script id="archify-i18n-data" type="application\/json">([\s\S]*?)<\/script>/;
const GUIDED_RE = /<script id="archify-guided-views-data" type="application\/json">([\s\S]*?)<\/script>/;
const CSS_LINK_RE = /<link[^>]*href="[^"]*archify\.css"[^>]*>/;
const JS_SRC_RE = /<script[^>]*src="[^"]*archify\.js"[^>]*><\/script>/;

const sha = s => createHash('sha1').update(s.replace(/\s+/g, ' ')).digest('hex').slice(0, 12);
const pages = () => PAGE_DIRS.flatMap(dir =>
  readdirSync(dir).filter(f => f.endsWith('.html')).map(f => join(dir, f)));

/** Collect one block from every page and refuse to guess if they diverge. */
function collect(files, re, label) {
  const seen = new Map();
  for (const file of files) {
    const m = readFileSync(file, 'utf8').match(re);
    if (!m) continue;
    const key = sha(m[1]);
    if (!seen.has(key)) seen.set(key, { body: m[1], files: [] });
    seen.get(key).files.push(relative(ROOT, file));
  }
  if (seen.size === 0) return null;
  if (seen.size > 1) {
    const detail = [...seen.values()].map(v => `  ${sha(v.body)} x${v.files.length} (${v.files[0]})`).join('\n');
    throw new Error(`${label} differs between pages — refusing to hoist one variant over another:\n${detail}`);
  }
  return [...seen.values()][0].body;
}

/** Shared runtime file: recreate the JSON data elements, then run the engine. */
function runtimeSource(engine, guidedJson, i18nJson) {
  return `/* Archify viewer runtime — shared by every diagram page.
 * Generated by tools/hoist-runtime.mjs; edit the generator, not this file. */
(function () {
  var DATA = { guidedViews: ${guidedJson}, i18n: ${i18nJson} };
  function ensureData(id, value) {
    if (document.getElementById(id)) return;
    var el = document.createElement('script');
    el.id = id;
    el.type = 'application/json';
    el.textContent = JSON.stringify(value);
    (document.body || document.documentElement).appendChild(el);
  }
  ensureData('archify-guided-views-data', DATA.guidedViews);
  ensureData('archify-i18n-data', DATA.i18n);
})();
${engine}`;
}

const relRef = (file, target) => relative(dirname(file), target).split('\\').join('/');

export function hoistRuntime({ selfContained = false, check = false, quiet = false } = {}) {
  const files = pages();
  if (!files.length) throw new Error('no diagram pages found');

  if (selfContained) {
    if (!existsSync(CSS_OUT) || !existsSync(JS_OUT))
      throw new Error('no shared runtime to inline — run without --self-contained first');
    const css = readFileSync(CSS_OUT, 'utf8');
    const js = readFileSync(JS_OUT, 'utf8');
    let changed = 0;
    for (const file of files) {
      let html = readFileSync(file, 'utf8');
      if (!CSS_LINK_RE.test(html) && !JS_SRC_RE.test(html)) continue;
      const before = html;
      html = html.replace(CSS_LINK_RE, () => `<style>${css}</style>`);
      html = html.replace(JS_SRC_RE, () => `<script>${js}</script>`);
      if (html !== before) { writeFileSync(file, html); changed++; }
    }
    if (!quiet) console.log(`self-contained: re-inlined ${changed} page(s) from archify.css + archify.js`);
    return { mode: 'self-contained', pages: files.length, changed };
  }

  // Collect the shared blocks from the pages that still carry them.
  const inline = files.filter(f => {
    const html = readFileSync(f, 'utf8');
    return STYLE_RE.test(html) && !CSS_LINK_RE.test(html);
  });

  if (check) {
    const pending = files.filter(f => {
      const html = readFileSync(f, 'utf8');
      return !CSS_LINK_RE.test(html) || !JS_SRC_RE.test(html);
    });
    if (pending.length && !quiet)
      console.log(`${pending.length} page(s) not hoisted, e.g. ${relative(ROOT, pending[0])}`);
    return { mode: 'check', pages: files.length, pending: pending.length };
  }

  let css = null, engine = null, i18n = null, guided = null;
  if (inline.length) {
    css = collect(inline, STYLE_RE, 'stylesheet');
    engine = collect(inline, ENGINE_RE, 'engine script');
    i18n = collect(inline, I18N_RE, 'i18n data');
    guided = collect(inline, GUIDED_RE, 'guided-views data');
  } else {
    // Already hoisted: keep the existing shared files.
    if (!existsSync(CSS_OUT) || !existsSync(JS_OUT))
      throw new Error('pages reference archify.css/archify.js but the shared files are missing');
    css = readFileSync(CSS_OUT, 'utf8');
    engine = readFileSync(JS_OUT, 'utf8');
  }

  if (css && engine) {
    mkdirSync(DIAGRAMS, { recursive: true });
    writeFileSync(CSS_OUT, css.trimStart() + '\n');
    if (i18n !== null && guided !== null) writeFileSync(JS_OUT, runtimeSource(engine, guided, i18n) + '\n');
    else if (!existsSync(JS_OUT)) writeFileSync(JS_OUT, engine + '\n');
  }

  let changed = 0, beforeBytes = 0, afterBytes = 0;
  for (const file of files) {
    let html = readFileSync(file, 'utf8');
    beforeBytes += Buffer.byteLength(html);
    const before = html;
    const cssHref = relRef(file, CSS_OUT);
    const jsHref = relRef(file, JS_OUT);
    if (STYLE_RE.test(html) && !CSS_LINK_RE.test(html))
      html = html.replace(STYLE_RE, () => `<link rel="stylesheet" href="${cssHref}">`);
    if (ENGINE_RE.test(html) && !JS_SRC_RE.test(html)) {
      html = html.replace(I18N_RE, '');
      html = html.replace(GUIDED_RE, '');
      html = html.replace(ENGINE_RE, () => `<script src="${jsHref}"></script>`);
    }
    if (html !== before) { writeFileSync(file, html); changed++; }
    afterBytes += Buffer.byteLength(html);
  }

  const stats = {
    mode: 'hoist',
    pages: files.length,
    changed,
    beforeMB: +(beforeBytes / 1048576).toFixed(1),
    afterMB: +(afterBytes / 1048576).toFixed(1),
    sharedKB: +((Buffer.byteLength(readFileSync(CSS_OUT)) + Buffer.byteLength(readFileSync(JS_OUT))) / 1024).toFixed(0),
  };
  if (!quiet)
    console.log(`hoisted runtime: ${files.length} pages, ${changed} rewritten, ` +
      `${stats.beforeMB} MB -> ${stats.afterMB} MB (+${stats.sharedKB} KB shared)`);
  return stats;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  try {
    const stats = hoistRuntime({
      selfContained: process.argv.includes('--self-contained'),
      check: process.argv.includes('--check'),
    });
    if (stats.pending) process.exit(1);
  } catch (e) {
    console.error('hoist-runtime: ' + e.message);
    process.exit(1);
  }
}
